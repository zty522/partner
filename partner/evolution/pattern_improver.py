    # ── Plan rendering ─────────────────────────────────────────────────────

    @classmethod
    def format_plan_human_readable(
        cls, plans: list[dict[str, Any]]
    ) -> str:
        """Format improvement plans as a human-readable text report."""
        lines: list[str] = []
        lines.append("=" * 60)
        lines.append("📋 代码学习改进方案")
        lines.append("=" * 60)

        risk_icons = {"high": "🔴", "medium": "🟡", "low": "🟢"}

        for i, plan in enumerate(plans, 1):
            lines.append("")
            lines.append(f"{'─' * 40}")
            lines.append(
                f"{risk_icons.get(plan.get('risk_level', 'low'), '⚪')} "
                f"方案 #{i}: {plan.get('description', '')[:100]}"
            )
            lines.append(f"  文件: {plan.get('target_file', '?')}")
            lines.append(f"  类型: {plan.get('change_type', 'modify')}")
            lines.append(f"  风险: {plan.get('risk_level', '?')} | "
                         f"预估: {plan.get('estimated_effort', '?')}")
            lines.append(f"  影响: {plan.get('expected_impact', '')}")

            deps = plan.get('dependencies', [])
            if deps:
                lines.append(f"  依赖: {', '.join(deps)}")

            code = plan.get('code_diff', '')
            if code:
                lines.append(f"  代码片段:")
                code_lines = code.strip().split("\n")
                for cl in code_lines[:8]:
                    lines.append(f"    {cl}")
                if len(code_lines) > 8:
                    lines.append(f"    ... ({len(code_lines)} 行)")

        lines.append("")
        lines.append("=" * 60)
        lines.append(f"共 {len(plans)} 个改进方案")
        lines.append("=" * 60)

        return "\n".join(lines)

    @classmethod
    def format_plan_json(
        cls, plans: list[dict[str, Any]]
    ) -> str:
        """Format improvement plans as a JSON string."""
        import json
        return json.dumps(
            plans,
            indent=2,
            ensure_ascii=False,
            default=str,
        )
