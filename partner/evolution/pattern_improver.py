class PatternImprover:
    """Generate concrete, executable improvement plans from gap analysis.

    All code generation is done via LLM (HermesAdapter). No hardcoded
    templates or preset pattern matching.
    """

    _plan_counter: int = 0

    # ── Public API ─────────────────────────────────────────────────────────

    @classmethod
    async def generate_improvements(
        cls,
        gaps: list[dict[str, Any]],
        partner_gui_root: str | Path | None = None,
        progress_callback=None,
    ) -> list[dict[str, Any]]:
        """Convert gap entries into concrete, executable improvement plans.

        For 2+ gaps, uses a SINGLE batched LLM call instead of N sequential
        calls.  This reduces the 12-minute synchronous block to ~30 seconds.

        All HTTP calls are dispatched via asyncio.to_thread() so the event loop
        remains free for progress callbacks and message processing.

        Each plan specifies:
        - Exact file path to modify
        - What kind of change (modify, new file, new class)
        - The specific code diff/snippet
        - Expected impact
        - Risk level and estimated effort

        Args:
            gaps: List of gap dicts from PatternComparator.compare().
            partner_gui_root: Override Partner GUI root path.
            progress_callback: Optional callable(msg) for progress reporting.

        Returns:
            List of structured improvement plan dicts.
        """
        cls._plan_counter = 0
        gui_root = Path(partner_gui_root) if partner_gui_root else PARTNER_GUI_ROOT

        if len(gaps) >= 2:
            # ── Batch mode: single LLM call for all gaps ──
            if progress_callback:
                await progress_callback(f"💡 批量生成 {len(gaps)} 个改进方案（一次 LLM 调用，预计 30-60 秒）...")
            plans = await cls._generate_plans_batch(gaps, gui_root)
        else:
            # ── Sequential mode: one LLM call per gap (1 gap only) ──
            plans = []
            for idx, gap in enumerate(gaps):
                plan = await cls._gap_to_plan(gap, gui_root)
                if plan:
                    plans.append(plan)
                if progress_callback and (idx + 1) % 5 == 0:
                    await progress_callback(
                        f"💡 正在生成改进方案... ({idx + 1}/{len(gaps)})"
                    )

        # Sort by risk level (high priority first)
        risk_order = {"high": 0, "medium": 1, "low": 2}
        plans.sort(key=lambda p: risk_order.get(p.get("risk_level", "low"), 99))

        logger.info(
            "Generated %d improvement plans (high=%d, med=%d, low=%d)",
            len(plans),
            sum(1 for p in plans if p.get("risk_level") == "high"),
            sum(1 for p in plans if p.get("risk_level") == "medium"),
            sum(1 for p in plans if p.get("risk_level") == "low"),
        )

        return plans

    @classmethod
    async def generate_improvement_plans(
        cls,
        gaps: list[dict[str, Any]],
    ) -> list[ImprovementPlan]:
        """Generate ImprovementPlan objects (compatible with SelfEvolveEngine).

        Uses the existing ImprovementPlan dataclass so these plans can flow
        into the existing Implementation module.

        Args:
            gaps: List of gap dicts from PatternComparator.compare().

        Returns:
            List of ImprovementPlan objects.
        """
        cls._plan_counter = 0
        plans: list[ImprovementPlan] = []

        for gap in gaps:
            plan_dict = await cls._gap_to_plan(gap, PARTNER_GUI_ROOT)
            if not plan_dict:
                continue

            # Determine change_type and risk for ImprovementPlan format
            risk = plan_dict.get("risk_level", "medium")
            change_type = plan_dict.get("change_type", "modify_function")
            if change_type == "new_file":
                change_type = "add_feature"
            elif change_type == "new_class":
                change_type = "add_feature"

            plans.append(ImprovementPlan(
                id=f"plan_im{cls._plan_counter:03d}",
                target_module=plan_dict["target_file"],
                change_type=change_type,
                function_name="",
                new_code=plan_dict.get("code_diff", ""),
                description=plan_dict["description"],
                risk_level=risk,
            ))

        logger.info(
            "Generated %d ImprovementPlan objects from %d gaps",
            len(plans), len(gaps),
        )
        return plans

    # ── Gap → Plan conversion ──────────────────────────────────────────────

    @classmethod
    async def _gap_to_plan(
        cls, gap: dict[str, Any], gui_root: Path
    ) -> dict[str, Any] | None:
        """Convert a single gap dict into a concrete improvement plan."""
        cls._plan_counter += 1

        category = gap.get("category", "")
        pattern_name = gap.get("external_pattern", "")
        priority = gap.get("priority", "medium")

        # Determine which Partner file to modify
        target_file, change_type = cls._determine_target(category, pattern_name)

        # Generate specific code suggestion via LLM
        code_diff = await cls._generate_code(pattern_name, category, change_type, target_file)

        # Build description
        description = (
            f"[{category}] {pattern_name}："
            f"{gap.get('partner_status', '')}。"
            f"{gap.get('suggestion', '')}"
        )

        # Assess risk and effort
        risk_level, estimated_effort = cls._assess_risk_and_effort(
            category, change_type, priority,
        )

        # Determine expected impact
        expected_impact = cls._determine_impact(category, pattern_name)

        # Check for dependencies
        dependencies = cls._determine_dependencies(category, pattern_name, target_file)

        plan: dict[str, Any] = {
            "plan_id": f"plan_{cls._plan_counter:03d}",
            "target_file": target_file,
            "change_type": change_type,
            "description": description,
            "code_diff": code_diff,
            "expected_impact": expected_impact,
            "risk_level": risk_level,
            "estimated_effort": estimated_effort,
            "dependencies": dependencies,
            "category": category,
            "gap_id": gap.get("gap_id", ""),
            "external_source": gap.get("external_source", ""),
            "external_file": gap.get("external_file", ""),
        }

        return plan

