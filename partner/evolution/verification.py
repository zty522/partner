def _aggregate_metrics(metrics: list[TaskMetrics]) -> dict[str, float]:
    """Aggregate a list of :class:`TaskMetrics` into summary statistics.

    Args:
        metrics: List of individual task metrics.

    Returns:
        Dict with keys ``avg_time``, ``success_rate``, ``error_count``,
        and ``tasks_total``.
    """
    if not metrics:
        return {"avg_time": 0.0, "success_rate": 0.0, "error_count": 0.0, "tasks_total": 0.0}

    n = len(metrics)
    total_time = sum(m.avg_time for m in metrics)
    total_success = sum(m.success_rate for m in metrics)
    total_errors = sum(m.error_count for m in metrics)

    return {
        "avg_time": total_time / n,
        "success_rate": total_success / n,
        "error_count": float(total_errors),
        "tasks_total": float(n),
    }


def _compute_improvements(
    before: dict[str, float],
    after: dict[str, float],
) -> dict[str, float]:
    """Compute before/after deltas for each metric.

    Positive values mean improvement (faster time, higher success rate).
    Negative values mean regression.

    Args:
        before: Summary stats from the *before* run.
        after: Summary stats from the *after* run.

    Returns:
        Dict with keys:
        - ``avg_time_delta``: Change in average time (seconds).
          Negative = faster (improvement).
        - ``avg_time_delta_pct``: Percentage change in average time.
          Negative = faster (improvement).
        - ``success_rate_delta``: Change in success rate (0.0–1.0).
          Positive = improvement.
        - ``success_rate_delta_pct``: Percentage change in success rate.
          Positive = improvement.
        - ``error_count_delta``: Change in error count.
          Negative = fewer errors (improvement).
    """
    before_time = before.get("avg_time", 0.0)
    after_time = after.get("avg_time", 0.0)
    before_rate = before.get("success_rate", 0.0)
    after_rate = after.get("success_rate", 0.0)
    before_errors = before.get("error_count", 0.0)
    after_errors = after.get("error_count", 0.0)

    time_delta = after_time - before_time  # negative = faster (good)
    rate_delta = after_rate - before_rate  # positive = better
    error_delta = after_errors - before_errors  # negative = fewer errors (good)

    time_delta_pct = 0.0
    if before_time > 0:
        time_delta_pct = (time_delta / before_time) * 100.0

    rate_delta_pct = 0.0
    if before_rate > 0:
        rate_delta_pct = (rate_delta / before_rate) * 100.0
    elif after_rate > 0:
        rate_delta_pct = 100.0  # went from 0 to something positive

    return {
        "avg_time_delta": round(time_delta, 3),
        "avg_time_delta_pct": round(time_delta_pct, 1),
        "success_rate_delta": round(rate_delta, 3),
        "success_rate_delta_pct": round(rate_delta_pct, 1),
        "error_count_delta": round(error_delta, 1),
    }


def _determine_verdict(improvements: dict[str, float]) -> str:
    """Determine the verdict based on the computed improvements.

    The verdict is determined by:

    - **effective**: Average time improved by >= 10% AND success rate
      did not degrade by more than 10%.
    - **regressive**: Average time degraded by > 10% OR success rate
      dropped by > 10%.
    - **neutral**: All other cases (changes within the margin of noise).

    Args:
        improvements: Dict returned by :func:`_compute_improvements`.

    Returns:
        One of ``"effective"``, ``"neutral"``, or ``"regressive"``.
    """
    time_pct = improvements.get("avg_time_delta_pct", 0.0)
    rate_delta = improvements.get("success_rate_delta", 0.0)

    # Time improvement is negative (faster after)
    time_improved = time_pct <= -_TIME_IMPROVEMENT_THRESHOLD * 100.0
    time_regressed = time_pct > _TIME_IMPROVEMENT_THRESHOLD * 100.0
    rate_degraded = rate_delta < -_SUCCESS_RATE_DEGRADE_THRESHOLD

    if time_improved and not rate_degraded:
        return "effective"
    if time_regressed or rate_degraded:
        return "regressive"
    return "neutral"


