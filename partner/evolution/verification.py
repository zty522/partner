def generate_report(result: VerificationResult) -> str:
    """Generate a human-readable verification report from a result.

    The report includes:
    - Header with plan ID and timestamp
    - Per-task before/after comparison table
    - Summary statistics
    - Improvement deltas
    - Final verdict with justification

    Args:
        result: A :class:`VerificationResult` from :func:`run_verification`.

    Returns:
        A formatted string suitable for display or saving to a file.
    """
    return result.report if result.report else _build_report(
        plan_id=result.plan_id,
        before_metrics=result.before_metrics,
        after_metrics=result.after_metrics,
        stats_before=result.summary_stats.get("before", {}),
        stats_after=result.summary_stats.get("after", {}),
        improvements=result.improvements,
        verdict=result.verdict,
    )


def _build_report(
    *,
    plan_id: str,
    before_metrics: list[TaskMetrics],
    after_metrics: list[TaskMetrics],
    stats_before: dict[str, float],
    stats_after: dict[str, float],
    improvements: dict[str, float],
    verdict: str,
) -> str:
    """Build the full verification report string.

    Args:
        plan_id: Improvement plan identifier.
        before_metrics: List of before-task metrics.
        after_metrics: List of after-task metrics.
        stats_before: Aggregated before statistics.
        stats_after: Aggregated after statistics.
        improvements: Computed improvement deltas.
        verdict: The final verdict.

    Returns:
        Formatted report string.
    """
    lines: list[str] = []
    timestamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
    verdict_icon = {"effective": "✅", "neutral": "➡️", "regressive": "⚠️"}.get(verdict, "❓")

    # ── Header ─────────────────────────────────────────────────────────────
    lines.append("=" * 72)
    lines.append("  PARTNER SELF-EVOLUTION — VERIFICATION REPORT")
    lines.append("=" * 72)
    lines.append(f"  Plan ID:      {plan_id}")
    lines.append(f"  Timestamp:    {timestamp}")
    lines.append(f"  Tasks:        {len(before_metrics)}")
    lines.append(f"  Verdict:      {verdict_icon}  {verdict.upper()}")
    lines.append("")

    # ── Per-task Comparison ─────────────────────────────────────────────────
    lines.append("-" * 72)
    lines.append("  PER-TASK COMPARISON")
    lines.append("-" * 72)
    header = f"  {'Task':<40s} {'Before(s)':>10s} {'After(s)':>10s} {'Status':>10s}"
    lines.append(header)
    lines.append("  " + "-" * 72)

    for i in range(max(len(before_metrics), len(after_metrics))):
        before = before_metrics[i] if i < len(before_metrics) else None
        after = after_metrics[i] if i < len(after_metrics) else None

        task_label = ""
        before_time = 0.0
        after_time = 0.0
        status = ""

        if before and after:
            # Truncate task description for display
            task_label = before.task[:38] + ".." if len(before.task) > 40 else before.task
            before_time = before.avg_time
            after_time = after.avg_time
            # Determine per-task direction
            if after.success_rate > before.success_rate:
                status = "✅"
            elif after.success_rate < before.success_rate:
                status = "⚠️"
            elif after.avg_time < before.avg_time * 0.9:
                status = "✅"
            elif after.avg_time > before.avg_time * 1.1:
                status = "⚠️"
            else:
                status = "➡️"
        elif before:
            task_label = before.task[:38] + ".." if len(before.task) > 40 else before.task
            before_time = before.avg_time
            status = "❌ (after missing)"
        elif after:
            task_label = after.task[:38] + ".." if len(after.task) > 40 else after.task
            after_time = after.avg_time
            status = "❌ (before missing)"

        lines.append(f"  {task_label:<40s} {before_time:>8.2f}s {after_time:>8.2f}s {status:>10s}")

    lines.append("")

    # ── Summary Statistics ─────────────────────────────────────────────────
    lines.append("-" * 72)
    lines.append("  SUMMARY STATISTICS")
    lines.append("-" * 72)
    _add_stat_line(lines, "Average time (s)", stats_before.get("avg_time", 0.0), stats_after.get("avg_time", 0.0))
    _add_stat_line(lines, "Success rate", stats_before.get("success_rate", 0.0), stats_after.get("success_rate", 0.0), is_pct=True)
    _add_stat_line(lines, "Error count", stats_before.get("error_count", 0.0), stats_after.get("error_count", 0.0))
    lines.append("")

    # ── Improvement Deltas ─────────────────────────────────────────────────
    lines.append("-" * 72)
    lines.append("  IMPROVEMENT DELTAS")
    lines.append("-" * 72)
    _add_delta_line(lines, "Avg time delta", improvements.get("avg_time_delta", 0.0), "s", lower_better=True)
    _add_delta_line(lines, "Avg time delta (%)", improvements.get("avg_time_delta_pct", 0.0), "%", lower_better=True)
    _add_delta_line(lines, "Success rate delta", improvements.get("success_rate_delta", 0.0), "", lower_better=False)
    _add_delta_line(lines, "Error count delta", improvements.get("error_count_delta", 0.0), "count", lower_better=True)
    lines.append("")

    # ── Verdict ────────────────────────────────────────────────────────────
    lines.append("=" * 72)
    lines.append(f"  VERDICT: {verdict_icon}  {verdict.upper()}")
    lines.append("=" * 72)

    if verdict == "effective":
        lines.append("")
        lines.append("  The improvement plan produced measurable gains:")
        time_delta = improvements.get("avg_time_delta_pct", 0.0)
        rate_delta = improvements.get("success_rate_delta", 0.0)
        if time_delta < 0:
            lines.append(f"    - Execution time reduced by {abs(time_delta):.1f}%")
        if rate_delta > 0:
            lines.append(f"    - Success rate improved by {rate_delta * 100:.1f}%")
        lines.append("")
        lines.append("  Conclusion: The improvement should be retained.")

    elif verdict == "neutral":
        lines.append("")
        lines.append("  The improvement plan produced no significant change:")
        time_delta = improvements.get("avg_time_delta_pct", 0.0)
        rate_delta = improvements.get("success_rate_delta", 0.0)
        lines.append(f"    - Average time changed by {time_delta:+.1f}%")
        lines.append(f"    - Success rate changed by {rate_delta:+.3f}")
        lines.append("")
        lines.append("  Conclusion: The improvement is within the noise margin.")
        lines.append("  Consider collecting more data or refining the improvement.")

    elif verdict == "regressive":
        lines.append("")
        lines.append("  The improvement plan caused degradation:")
        time_delta = improvements.get("avg_time_delta_pct", 0.0)
        rate_delta = improvements.get("success_rate_delta", 0.0)
        if time_delta > 0:
            lines.append(f"    - Execution time increased by {time_delta:.1f}%")
        if rate_delta < 0:
            lines.append(f"    - Success rate dropped by {abs(rate_delta) * 100:.1f}%")
        lines.append("")
        lines.append("  Conclusion: The improvement should be rolled back or revised.")

    lines.append("")
    lines.append("-" * 72)
    lines.append("  End of report")
    lines.append("")

    return "\n".join(lines)


def _add_stat_line(lines: list[str], label: str, before_val: float, after_val: float, *, is_pct: bool = False) -> None:
    """Add a summary statistics line to the report."""
    fmt = ".3f" if not is_pct else ".1%"
    if is_pct:
        b_str = f"{before_val:.1%}"
        a_str = f"{after_val:.1%}"
    else:
        b_str = f"{before_val:.3f}"
        a_str = f"{after_val:.3f}"
    lines.append(f"  {label:<25s}  Before: {b_str:>10s}  After: {a_str:>10s}")


def _add_delta_line(lines: list[str], label: str, value: float, unit: str, *, lower_better: bool) -> None:
    """Add an improvement delta line with direction indicator."""
    if lower_better:
        direction = "↓" if value < 0 else ("↑" if value > 0 else "—")
    else:
        direction = "↑" if value > 0 else ("↓" if value < 0 else "—")
    sign = "+" if value > 0 else ""
    lines.append(f"  {label:<25s}  {sign}{value:.3f} {unit:<6s} {direction}")
